test("migrate 0.11 rewrites a 0.10 module into the three-file root, plain routes and a declaration the new core boots", async () => {
  const app = await fixture(old);
  const report = migrate(app.rootDir);

  // The record and the report.
  expect(report.mappings).toEqual({ probe: { limit: { variable: "PROBE_LIMIT", type: "number" }, mode: { variable: "PROBE_MODE", type: "enum" }, keep: { variable: "PROBE_KEEP", type: "string" } } });
  expect(report.todos.join("\n")).toMatch(/PROBE_KEEP became a setting but is still read elsewhere/);
  expect(report.todos.join("\n")).toMatch(/runtime\(\) kept through helpers\/runtime\.ts/);
  expect(report.todos.join("\n")).toMatch(/probe\.controllers\.ts: parameter properties became declared fields/);

  // Root: pnpm, scripts, flags, no tsx anywhere.
  const pkg = JSON.parse(await readFile(join(app.rootDir, "package.json"), "utf8"));
  expect(pkg).toMatchObject({ packageManager: "pnpm@10.28.0", pnpm: { overrides: { "pm2>js-yaml": "4.3.2" } }, scripts: { start: "node app.ts", worker: "node worker.ts", script: "node", spec: "tulipes spec --openapi docs/openapi.json" } });
  expect(pkg.workspaces).toBeUndefined();
  expect(pkg.devDependencies.tsx).toBeUndefined();
  expect(await readFile(join(app.rootDir, "pnpm-workspace.yaml"), "utf8")).toBe('packages:\n  - "modules/*"\n');
  expect(existsSync(join(app.rootDir, ".yarnrc.yml"))).toBe(false);
  expect(existsSync(join(app.rootDir, "types/config.d.ts"))).toBe(false);
  expect(JSON.parse(await readFile(join(app.rootDir, "tsconfig.json"), "utf8")).compilerOptions).toMatchObject({ allowImportingTsExtensions: true, rewriteRelativeImportExtensions: true, erasableSyntaxOnly: true });
  expect(await readFile(join(app.rootDir, "vitest.config.ts"), "utf8")).not.toContain("tsx");
  expect(await readFile(join(app.rootDir, "ecosystem.config.cjs"), "utf8")).toContain('interpreter: "node"');
  expect(await readFile(join(app.rootDir, "tests/parity.test.ts"), "utf8")).toContain('const context = (await boot({ inspect: true, mode: "backend", handleSignals: false, rootDir: import.meta.dirname })).ctx;');

  // The module root and its manifest.
  const manifest = JSON.parse(await readFile(join(app.rootDir, "modules/probe/package.json"), "utf8"));
  // The fixture injects PORT; the variables that became settings are gone, the one still read elsewhere stays.
  expect(manifest.tulipes.tier).toBe("app");
  expect(manifest.tulipes.env.filter((spec: { name: string }) => spec.name !== "PORT")).toEqual([{ name: "PROBE_KEEP", type: "string", default: "kept", description: "Read elsewhere too" }]);
  expect(manifest.exports).toEqual({ ".": "./lib/index.ts" });
  for (const gone of ["meta.variables.json", "index.ts", "schemas.ts"]) expect(existsSync(join(app.rootDir, "modules/probe", gone))).toBe(false);
  expect(await readFile(join(app.rootDir, "modules/probe/lib/index.ts"), "utf8")).toBe('export { helper } from "../helpers/helper.ts";\n');
  expect(existsSync(join(app.rootDir, "modules/probe/schemas/probe.schemas.ts"))).toBe(true);

  // The declaration, the lifecycle and the routes.
  const config = await readFile(join(app.rootDir, "modules/probe/module.config.ts"), "utf8");
  expect(config).toContain('limit: z.number().default(5).describe("How many"),');
  expect(config).toContain('mode: z.enum(["open","closed"]).default("open").describe("Which"),');
  expect(config).toContain('label: z.string().default("probe"),');
  expect(config).toContain("retries: z.number().default(3),");
  expect(config).not.toMatch(/onReady|ConfigCtx|Environment\.get/);
  const lifecycle = await readFile(join(app.rootDir, "modules/probe/bootstrap/probe.lifecycle.bootstrap.ts"), "utf8");
  expect(lifecycle).toContain('import { helper } from "../helpers/helper.ts";');
  expect(lifecycle).toContain("probeReady = helper(Number(config.probe?.limit));");
  expect(lifecycle).toContain("return async () => {");
  const routes = await readFile(join(app.rootDir, "modules/probe/routes/probe.routes.ts"), "utf8");
  expect(routes).toContain('import { ProbeController } from "../controllers/probe.controllers.ts";');
  expect(routes).toContain("export default function probeRoutes(ctx: BackendCtx): void {");
  expect(routes).toContain("const probe = new ProbeController(ctx);");
  expect(routes).toContain("probe.list());");
  expect(routes).toContain("const stamp = runtime(ctx, async ({ Environment }) => {");
  expect(routes).toContain('routes.mount(router, "/probe");');
  expect(routes).toContain('from "../schemas/probe.schemas.ts"');
  expect(routes).not.toContain("defineRoutes");
  expect(existsSync(join(app.rootDir, "modules/probe/helpers/runtime.ts"))).toBe(true);
  expect(await readFile(join(app.rootDir, "modules/probe/controllers/probe.controllers.ts"), "utf8")).toContain("private readonly ctx: Ctx;\n\n  constructor(ctx: Ctx) {\n    this.ctx = ctx;\n  }");

  // A second run finds nothing left to move.
  const again = migrate(app.rootDir);
  expect(again.changed.filter((line) => !line.startsWith("wrote config/migration"))).toEqual([]);

  // The migrated module boots on this core — declaration, bootstrap and routes alike.
  const handle = await app.boot({ listen: false });
  try {
    expect(handle.ctx.config.probe).toEqual({ limit: 5, mode: "open", keep: "kept", label: "probe", retries: 3 });
    expect((globalThis as { probeReady?: unknown }).probeReady).toBe(5);
    expect(handle.ctx.routes.all().map((record) => [record.method, record.path])).toEqual([["GET", "/probe/things"]]);
  } finally {
    await handle.shutdown();
  }
  expect((globalThis as { probeDown?: boolean }).probeDown).toBe(true);
});

test("config:import carries the env file's values for migrated settings into the file store, validated", async () => {
  const app = await fixture(old);
  migrate(app.rootDir);
  await app.write(".envs/.env.production", "PROBE_LIMIT=9\nPROBE_MODE=closed # inline comment\nPROBE_KEEP=\"quoted\"\n");

  const lines: string[] = [];
  const log = console.log;
  console.log = (...args: unknown[]) => { lines.push(args.join(" ")); };
  try {
    await runConfigImport(app.rootDir, { env: "production" });
  } finally {
    console.log = log;
  }
  expect(lines.join("\n")).toContain("probe: limit ← PROBE_LIMIT, mode ← PROBE_MODE, keep ← PROBE_KEEP");
  const stored = JSON.parse(await readFile(join(app.rootDir, "config/settings.production.json"), "utf8"));
  expect(stored.probe).toMatchObject({ values: { limit: 9, mode: "closed", keep: "quoted", label: "probe", retries: 3 }, version: 1, updated_by: { id: "config:import" } });

  // A value the schema refuses is reported, not written.
  await app.write(".envs/.env.production", "PROBE_MODE=sideways\n");
  const errors: string[] = [];
  const error = console.error;
  console.error = (...args: unknown[]) => { errors.push(args.join(" ")); };
  try {
    await runConfigImport(app.rootDir, { env: "production" });
  } finally {
    console.error = error;
    process.exitCode = 0;
  }
  expect(errors.join("\n")).toMatch(/probe: refused by the schema — mode:/);
  expect(JSON.parse(await readFile(join(app.rootDir, "config/settings.production.json"), "utf8")).probe.values.mode).toBe("closed");
});

test("the rewrites are precise", () => {
  const report = { changed: [], todos: [], mappings: {} };
  expect(rewriteSpecifiers(`import a from "./a.js";\nimport("../b/c.js");\nimport z from "zod/v4";\nconst s = "x.js";`)).toBe(`import a from "./a.ts";\nimport("../b/c.ts");\nimport z from "zod/v4";\nconst s = "x.js";`);
  expect(rewriteParameterProperties(`class A {\n  constructor(\n    private readonly authorize: (signal: AbortSignal) => Promise<boolean>,\n    readonly intervalMs: number,\n  ) {\n    this.x = 1;\n  }\n}`, "a.ts", report))
    .toBe(`class A {\n  private readonly authorize: (signal: AbortSignal) => Promise<boolean>;\n  readonly intervalMs: number;\n\n  constructor(authorize: (signal: AbortSignal) => Promise<boolean>, intervalMs: number) {\n    this.authorize = authorize;\n    this.intervalMs = intervalMs;\n    this.x = 1;\n  }\n}`);
  expect(rewriteParameterProperties(`class B { constructor(ctx: Ctx) { this.ctx = ctx; } }`, "b.ts", report)).toBe(`class B { constructor(ctx: Ctx) { this.ctx = ctx; } }`);
  expect(rewriteInspection(`import { boot, inspectRoutes } from "@tulipes/core/boot";\nconst c = await inspectRoutes({ rootDir: dir });`)).toBe(`import { boot } from "@tulipes/core/boot";\nconst c = (await boot({ inspect: true, mode: "backend", handleSignals: false, rootDir: dir })).ctx;`);
  expect(parseEnv("# c\nexport A=1\nB='two' # not a comment inside quotes\nC=three # comment\nD=\n")).toEqual({ A: "1", B: "two", C: "three", D: "" });
});
