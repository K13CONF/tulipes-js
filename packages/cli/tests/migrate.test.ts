test("config:import carries the env file's values for migrated settings into the file store, validated", async () => {
  const app = await fixture(old);
  migrate(app.rootDir);
  await app.write(".envs/.env.production", "PROBE_LIMIT=9\nPROBE_MODE=closed # inline comment\nPROBE_KEEP=\"quoted\"\n");

  const lines: string[] = [];
  const log = console.log;
  console.log = (...args: unknown[]) => { lines.push(args.join(" ")); };
  try {
    await runConfigImport(app.rootDir, { env: "production" });
  } finally {
    console.log = log;
  }
  expect(lines.join("\n")).toContain("probe: limit ← PROBE_LIMIT, mode ← PROBE_MODE, keep ← PROBE_KEEP");
  const stored = JSON.parse(await readFile(join(app.rootDir, "config/settings.production.json"), "utf8"));
  expect(stored.probe).toMatchObject({ values: { limit: 9, mode: "closed", keep: "quoted", label: "probe", retries: 3 }, version: 1, updated_by: { id: "config:import" } });

  // A value the schema refuses is reported, not written.
  await app.write(".envs/.env.production", "PROBE_MODE=sideways\n");
  const errors: string[] = [];
  const error = console.error;
  console.error = (...args: unknown[]) => { errors.push(args.join(" ")); };
  try {
    await runConfigImport(app.rootDir, { env: "production" });
  } finally {
    console.error = error;
    process.exitCode = 0;
  }
  expect(errors.join("\n")).toMatch(/probe: refused by the schema — mode:/);
  expect(JSON.parse(await readFile(join(app.rootDir, "config/settings.production.json"), "utf8")).probe.values.mode).toBe("closed");
});

test("the rewrites are precise", () => {
  const report = { changed: [], todos: [], mappings: {} };
  expect(rewriteSpecifiers(`import a from "./a.js";\nimport("../b/c.js");\nimport z from "zod/v4";\nconst s = "x.js";`)).toBe(`import a from "./a.ts";\nimport("../b/c.ts");\nimport z from "zod/v4";\nconst s = "x.js";`);
  expect(rewriteParameterProperties(`class A {\n  constructor(\n    private readonly authorize: (signal: AbortSignal) => Promise<boolean>,\n    readonly intervalMs: number,\n  ) {\n    this.x = 1;\n  }\n}`, "a.ts", report))
    .toBe(`class A {\n  private readonly authorize: (signal: AbortSignal) => Promise<boolean>;\n  readonly intervalMs: number;\n\n  constructor(authorize: (signal: AbortSignal) => Promise<boolean>, intervalMs: number) {\n    this.authorize = authorize;\n    this.intervalMs = intervalMs;\n    this.x = 1;\n  }\n}`);
  expect(rewriteParameterProperties(`class B { constructor(ctx: Ctx) { this.ctx = ctx; } }`, "b.ts", report)).toBe(`class B { constructor(ctx: Ctx) { this.ctx = ctx; } }`);
  expect(rewriteInspection(`import { boot, inspectRoutes } from "@tulipes/core/boot";\nconst c = await inspectRoutes({ rootDir: dir });`)).toBe(`import { boot } from "@tulipes/core/boot";\nconst c = (await boot({ inspect: true, mode: "backend", handleSignals: false, rootDir: dir })).ctx;`);
  expect(parseEnv("# c\nexport A=1\nB='two' # not a comment inside quotes\nC=three # comment\nD=\n")).toEqual({ A: "1", B: "two", C: "three", D: "" });
});

