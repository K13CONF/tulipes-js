// Generates one reference page per CLI command from `tulipes --help`, run from source so a
// new command or flag cannot go undocumented. Output is git-ignored; it is rebuilt every build.
import { execFileSync } from "node:child_process";
import { mkdirSync, rmSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { describe } from "../typedoc-seo.mjs";

const bin = fileURLToPath(new URL("../../packages/cli/src/bin.ts", import.meta.url));
const out = fileURLToPath(new URL("../src/content/docs/reference/cli/", import.meta.url));

export function parseHelp(help) {
  const commands = new Map(); // first word → { name, usages: [{ signature, summary, options[] }] }
  let current;
  for (const line of help.split("\n")) {
    const usage = line.match(/^ {2}tulipes (\S.*?)\s{2,}(\S.*)$/);
    if (usage) {
      const [, signature, summary] = usage;
      const word = signature.split(" ")[0];
      const name = word === "-v" ? "version" : word;
      if (!commands.has(name)) commands.set(name, { name, usages: [] });
      current = { signature: `tulipes ${signature}`, summary, options: [] };
      commands.get(name).usages.push(current);
    } else if (current && /^ {20,}\S/.test(line)) {
      const text = line.trim();
      // A wrapped summary continues on lines that are not flags and come before any flag.
      if (!text.startsWith("-") && current.options.length === 0) current.summary += ` ${text}`;
      else current.options.push(text);
    } else if (line.trim() === "") {
      current = undefined;
    }
  }
  return [...commands.values()];
}

const yaml = value => JSON.stringify(value);
// Prose is MDX: escape what would open a JSX tag or expression.
const sentence = text => (text.charAt(0).toUpperCase() + text.slice(1).replace(/\.?$/, ".")).replace(/[<{]/g, c => `\\${c}`);

export function renderPage({ name, usages }) {
  // The words every usage shares, placeholders and flags aside: "tulipes new module", "tulipes migrate".
  const words = usages.map(u => u.signature.split(" ").filter(w => !/^[[<]/.test(w) && (w === "-v" || !w.startsWith("-"))));
  const title = words[0].filter((w, i) => words.every(ws => ws[i] === w)).join(" ");
  const body = usages.map(({ signature, summary, options }) => [
    usages.length > 1 ? `## \`${signature}\`\n` : "",
    sentence(summary),
    "",
    "```sh",
    signature,
    "```",
    ...(options.length ? ["", usages.length > 1 ? "### Options" : "## Options", "", "```txt", ...options, "```"] : []),
  ].join("\n"));
  return [
    "---",
    `title: ${yaml(title)}`,
    `description: ${yaml(describe(`The ${title} command of the Tulipes CLI`, usages[0].summary, " Usage and every option, generated from the CLI's own help."))}`,
    "editUrl: false",
    "---",
    "",
    "{/* Generated by site/scripts/cli-reference.mjs from `tulipes --help`. Do not edit. */}",
    "",
    body.join("\n\n"),
    "",
  ].join("\n");
}

if (import.meta.url === `file://${process.argv[1]}`) {
  const help = execFileSync(process.execPath, [bin, "--help"], { encoding: "utf8" });
  const commands = parseHelp(help);
  if (commands.length < 10) throw new Error(`Parsed only ${commands.length} commands from tulipes --help; the format changed`);
  rmSync(out, { recursive: true, force: true });
  mkdirSync(out, { recursive: true });
  for (const command of commands) writeFileSync(`${out}${command.name.replace(":", "-")}.mdx`, renderPage(command));
  console.log(`CLI reference: ${commands.length} command pages.`);
}
